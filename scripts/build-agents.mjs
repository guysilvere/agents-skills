#!/usr/bin/env node
/**
 * scripts/build-agents.mjs
 * Génère les 9 fichiers agents (3 rôles × 3 outils) depuis agents-src/
 *
 * Usage:
 *   node scripts/build-agents.mjs         # Génère les fichiers
 *   node scripts/build-agents.mjs --check # Vérifie la parité sans écrire (CI / pré-vol)
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, join } from 'node:path';

const ROOT_DIR = resolve(import.meta.dirname, '..');
const AGENTS_SRC = join(ROOT_DIR, 'agents-src');

const TARGETS = ['opencode', 'antigravity', 'claude'];
const ROLES = ['lead-dev', 'ops-quality', 'integrations'];

const isCheck = process.argv.includes('--check');

/**
 * Filtre les blocs conditionnels <!-- only:<target> --> et <!-- except:<target> -->
 */
function filterBodyForTarget(body, target) {
  // 1. Blocs <!-- only:<tool> -->...<!-- /only -->
  let filtered = body.replace(/<!--\s*only:([a-z0-9_-]+)\s*-->([\s\S]*?)<!--\s*\/only\s*-->/gi, (match, tool, content) => {
    return tool.toLowerCase() === target.toLowerCase() ? content.trim() : '';
  });

  // 2. Blocs <!-- except:<tool> -->...<!-- /except -->
  filtered = filtered.replace(/<!--\s*except:([a-z0-9_-]+)\s*-->([\s\S]*?)<!--\s*\/except\s*-->/gi, (match, tool, content) => {
    return tool.toLowerCase() === target.toLowerCase() ? '' : content.trim();
  });

  // Normalisation des sauts de ligne multiples consécutifs
  return filtered.replace(/\n{3,}/g, '\n\n').trim();
}

/**
 * Construit le contenu final de l'agent
 */
function buildAgentContent(target, role) {
  const bodyPath = join(AGENTS_SRC, `${role}.body.md`);
  const frontmatterPath = join(AGENTS_SRC, 'frontmatter', target, `${role}.yaml`);

  if (!existsSync(bodyPath)) {
    throw new Error(`Fichier corps introuvable : ${bodyPath}`);
  }
  if (!existsSync(frontmatterPath)) {
    throw new Error(`Frontmatter introuvable : ${frontmatterPath}`);
  }

  const rawBody = readFileSync(bodyPath, 'utf8');
  const rawFrontmatter = readFileSync(frontmatterPath, 'utf8').trim();
  const processedBody = filterBodyForTarget(rawBody, target);

  return `---
${rawFrontmatter}
---
<!-- GENERATED BY scripts/build-agents.mjs — EDIT agents-src/ -->

${processedBody}
`;
}

// Exécution
let hasDiff = false;
const diffs = [];

for (const target of TARGETS) {
  for (const role of ROLES) {
    const destPath = join(ROOT_DIR, target, 'agents', `${role}.md`);
    const expectedContent = buildAgentContent(target, role);

    if (isCheck) {
      if (!existsSync(destPath)) {
        hasDiff = true;
        diffs.push(`Fichier manquant : ${destPath}`);
      } else {
        const currentContent = readFileSync(destPath, 'utf8');
        if (currentContent !== expectedContent) {
          hasDiff = true;
          diffs.push(`Désynchronisé : ${destPath}`);
        }
      }
    } else {
      writeFileSync(destPath, expectedContent, 'utf8');
      console.log(`✓ Généré : ${target}/agents/${role}.md`);
    }
  }
}

if (isCheck) {
  if (hasDiff) {
    console.error('❌ Échec de la vérification des agents : les fichiers suivants diffèrent de agents-src/ :');
    for (const d of diffs) {
      console.error(`  - ${d}`);
    }
    console.error('\nExécutez `node scripts/build-agents.mjs` pour régénérer les 9 agents.');
    process.exit(1);
  } else {
    console.log('✅ 9/9 agents synchronisés avec agents-src/');
    process.exit(0);
  }
} else {
  console.log('✅ Génération terminée avec succès (9 agents générés).');
}
